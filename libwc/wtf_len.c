void wtf_len_set(size_t i, wc_uint8 l)
{
    WTF_LEN_MAP[i] = l;
}

size_t wtf_len1(wc_uchar* p)
{
    size_t len, len_max = WTF_LEN_MAP[*p];

    for (len = 0; *(p + len); len++)
        if (len == len_max)
            break;
    if (len == 0)
        len = 1;
    return len;
}

size_t wtf_len(const wc_uchar* p)
{
    const wc_uchar* q = p;
    const wc_uchar* strz = p + strlen((char*)p);

    q += WTF_LEN_MAP[*q];
    while (q < strz && wtf_width(q) == 0)
        q += WTF_LEN_MAP[*q];
    return q - p;
}

int wtf_strwidth(wc_uchar* p)
{
    int w = 0;
    wc_uchar* q = p + strlen((const char*)p);
    while (p < q) {
        w += wtf_width(p);
        p += WTF_LEN_MAP[*p];
    }
    return w;
}


